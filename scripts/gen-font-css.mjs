/**
 * Generates src/styles/design/fonts.css from the fontsource packages: only the subsets we
 * self-host (Latin, Latin Extended, Arabic), URLs rewritten to /fonts/ (relative to
 * /styles/site.css), and font-display: optional — a late font is never swapped in, so text never
 * shifts (zero CLS). Run after changing the typefaces: node scripts/gen-font-css.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const FACES = [
  ['outfit', 'Outfit', ['latin', 'latin-ext'], false],
  ['jetbrains-mono', 'JetBrains Mono', ['latin', 'latin-ext'], false],
  ['noto-sans-arabic', 'Noto Sans Arabic', ['arabic'], false],
];

function faces(pkg, family, subsets, italic) {
  const css = fs.readFileSync(path.resolve('node_modules/@fontsource-variable', pkg, 'index.css'), 'utf8')
    + (italic && fs.existsSync(path.resolve('node_modules/@fontsource-variable', pkg, 'wght-italic.css')) ? fs.readFileSync(path.resolve('node_modules/@fontsource-variable', pkg, 'wght-italic.css'), 'utf8') : '');
  const out = [];
  for (const block of css.split('@font-face').slice(1)) {
    const file = /url\(\.\/files\/([^)]+)\)/.exec(block)?.[1];
    if (!file) continue;
    const subset = subsets.find((s) => file === `${pkg}-${s}-wght-normal.woff2` || file === `${pkg}-${s}-wght-italic.woff2`);
    if (!subset) continue;
    const style = file.includes('italic') ? 'italic' : 'normal';
    const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
    const weight = /font-weight:\s*([^;]+);/.exec(block)?.[1] ?? '100 900';
    out.push(`@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n  font-display: optional;\n  src: url(../fonts/${file}) format('woff2');\n  unicode-range: ${range};\n}`);
  }
  if (!out.length) throw new Error(`no faces for ${pkg}`);
  return out;
}
const css = ['/* Generated by scripts/gen-font-css.mjs — do not edit by hand. */', ...FACES.flatMap((f) => faces(...f))].join('\n\n');
fs.writeFileSync('src/styles/design/fonts.css', css + '\n');
console.log(`design/fonts.css: ${css.match(/@font-face/g).length} faces`);
